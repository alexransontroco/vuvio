function resolveUpcomingStart(day, time) {
  const now = new Date();
  const [hours = 9, minutes = 0] = String(time).split(':').map(Number);
  const start = new Date(now);
  start.setHours(hours, minutes, 0, 0);

  if (day === 'TMRW') {
    start.setDate(start.getDate() + 1);
  }

  if (day === 'TODAY' && start.getTime() <= now.getTime()) {
    start.setDate(start.getDate() + 1);
  }

  return start.toISOString();
}

function creatorFromWho(who) {
  const [creatorName = 'Vuvio creator', locationLabel = 'Location to be confirmed'] = String(who ?? '').split(' - ').map((part) => part.trim());
  return { creatorName, locationLabel };
}

